import { useState } from 'react'
import { jsPDF } from 'jspdf'
import autoTable from 'jspdf-autotable'

/**
 * TaskReportModal - Supplementary Problem 1:
 * Heavy third-party component leveraging `jspdf` and `jspdf-autotable` (~350+ kB).
 * Loaded dynamically on-demand using React.lazy() and Suspense so the heavy PDF
 * library is excluded from the initial bundle and initial route chunks.
 */
export default function TaskReportModal({ tasks = [], userEmail = '', onClose }) {
  const [generating, setGenerating] = useState(false)

  const total = tasks.length
  const completed = tasks.filter((t) => (t.status === 'completed' || t.completed)).length
  const working = tasks.filter((t) => t.status === 'working').length
  const pending = tasks.filter((t) => !t.completed && (!t.status || t.status === 'pending')).length
  const completionRate = total > 0 ? Math.round((completed / total) * 100) : 0

  const handleDownloadPdf = () => {
    try {
      setGenerating(true)
      const doc = new jsPDF()

      // Header Banner
      doc.setFillColor(37, 99, 235) // #2563eb
      doc.rect(0, 0, 210, 28, 'F')
      doc.setTextColor(255, 255, 255)
      doc.setFontSize(18)
      doc.setFont('helvetica', 'bold')
      doc.text('TASK MANAGEMENT SYSTEM - PERFORMANCE REPORT', 14, 18)

      // Metadata
      doc.setFontSize(10)
      doc.setFont('helvetica', 'normal')
      doc.setTextColor(70, 70, 70)
      const generatedAt = new Date().toLocaleString()
      doc.text(`Generated For: ${userEmail || 'Authenticated User'}`, 14, 38)
      doc.text(`Generated Date: ${generatedAt}`, 14, 44)
      doc.text(`Course: Advanced Web Development Frameworks (ITUE301)`, 14, 50)
      doc.text(`Student: Visrut Jajadiya (Practical 8 Performance Optimization)`, 14, 56)

      // Summary Table
      autoTable(doc, {
        startY: 62,
        head: [['Metric', 'Value', 'Status / Detail']],
        body: [
          ['Total Tasks', total.toString(), 'All registered tasks in collection'],
          ['Completed Tasks', completed.toString(), `${completionRate}% overall completion rate`],
          ['In-Progress (Working)', working.toString(), 'Tasks currently being processed'],
          ['Pending Tasks', pending.toString(), 'Tasks queued for future action'],
        ],
        theme: 'grid',
        headStyles: { fillColor: [37, 99, 235], textColor: 255, fontStyle: 'bold' },
        styles: { fontSize: 10, cellPadding: 4 },
      })

      // Task Items Detail Table
      const taskRows = tasks.map((t, idx) => [
        (idx + 1).toString(),
        t.title || 'Untitled',
        (t.priority || 'medium').toUpperCase(),
        (t.status || (t.completed ? 'completed' : 'pending')).toUpperCase(),
        t.createdAt ? new Date(t.createdAt).toLocaleDateString() : 'N/A',
      ])

      autoTable(doc, {
        startY: doc.lastAutoTable ? doc.lastAutoTable.finalY + 12 : 110,
        head: [['#', 'Task Title', 'Priority', 'Status', 'Created On']],
        body: taskRows.length > 0 ? taskRows : [['-', 'No tasks available', '-', '-', '-']],
        theme: 'striped',
        headStyles: { fillColor: [30, 41, 59], textColor: 255, fontStyle: 'bold' },
        styles: { fontSize: 9, cellPadding: 3.5 },
        columnStyles: {
          0: { cellWidth: 10, halign: 'center' },
          1: { cellWidth: 80 },
          2: { cellWidth: 26, halign: 'center' },
          3: { cellWidth: 32, halign: 'center' },
          4: { cellWidth: 35, halign: 'center' },
        },
      })

      // Footer
      const pageCount = doc.getNumberOfPages()
      for (let i = 1; i <= pageCount; i++) {
        doc.setPage(i)
        doc.setFontSize(8)
        doc.setTextColor(140, 140, 140)
        doc.text(
          `Page ${i} of ${pageCount} • Generated by Lazy-Loaded jsPDF Module (Charotar University of Science and Technology)`,
          14,
          290
        )
      }

      doc.save(`Task_Manager_Report_${Date.now()}.pdf`)
    } catch (err) {
      console.error('Error generating PDF:', err)
      alert('Failed to generate PDF report. Check browser console.')
    } finally {
      setGenerating(false)
    }
  }

  return (
    <div className="modal-overlay" role="dialog" aria-modal="true" aria-labelledby="report-modal-title">
      <div className="modal-card panel report-modal-panel">
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '16px' }}>
          <div>
            <span className="badge" style={{ background: 'rgba(37,99,235,0.1)', color: '#2563eb', fontWeight: 600 }}>
              Practical 8 Supplementary
            </span>
            <h3 id="report-modal-title" style={{ margin: '6px 0 2px 0', fontSize: '1.35rem' }}>
              Task Analytics &amp; PDF Report
            </h3>
            <p style={{ margin: 0, fontSize: '0.85rem', color: 'var(--text)' }}>
              ⚡ This component and the <code>jspdf</code> (~350 kB) library were lazy-loaded on-demand!
            </p>
          </div>
          <button
            type="button"
            className="ghost-button"
            onClick={onClose}
            aria-label="Close modal"
            style={{ fontSize: '1.2rem', padding: '6px 12px' }}
          >
            ✕
          </button>
        </div>

        {/* Analytics KPI grid */}
        <div style={{
          display: 'grid',
          gridTemplateColumns: 'repeat(auto-fit, minmax(110px, 1fr))',
          gap: '12px',
          margin: '16px 0',
        }}>
          <div className="stat-card" style={{ padding: '12px', borderRadius: '10px', background: 'var(--card-bg, #f8fafc)', border: '1px solid var(--border)' }}>
            <span style={{ fontSize: '0.75rem', color: 'var(--text)', textTransform: 'uppercase' }}>Total Tasks</span>
            <div style={{ fontSize: '1.5rem', fontWeight: 700, marginTop: '4px' }}>{total}</div>
          </div>
          <div className="stat-card" style={{ padding: '12px', borderRadius: '10px', background: 'var(--card-bg, #f8fafc)', border: '1px solid var(--border)' }}>
            <span style={{ fontSize: '0.75rem', color: '#16a34a', textTransform: 'uppercase' }}>Completed</span>
            <div style={{ fontSize: '1.5rem', fontWeight: 700, marginTop: '4px', color: '#16a34a' }}>{completed}</div>
          </div>
          <div className="stat-card" style={{ padding: '12px', borderRadius: '10px', background: 'var(--card-bg, #f8fafc)', border: '1px solid var(--border)' }}>
            <span style={{ fontSize: '0.75rem', color: '#2563eb', textTransform: 'uppercase' }}>In Progress</span>
            <div style={{ fontSize: '1.5rem', fontWeight: 700, marginTop: '4px', color: '#2563eb' }}>{working}</div>
          </div>
          <div className="stat-card" style={{ padding: '12px', borderRadius: '10px', background: 'var(--card-bg, #f8fafc)', border: '1px solid var(--border)' }}>
            <span style={{ fontSize: '0.75rem', color: '#d97706', textTransform: 'uppercase' }}>Pending</span>
            <div style={{ fontSize: '1.5rem', fontWeight: 700, marginTop: '4px', color: '#d97706' }}>{pending}</div>
          </div>
          <div className="stat-card" style={{ padding: '12px', borderRadius: '10px', background: 'var(--card-bg, #f8fafc)', border: '1px solid var(--border)' }}>
            <span style={{ fontSize: '0.75rem', color: 'var(--text)', textTransform: 'uppercase' }}>Completion</span>
            <div style={{ fontSize: '1.5rem', fontWeight: 700, marginTop: '4px' }}>{completionRate}%</div>
          </div>
        </div>

        {/* Progress Bar */}
        <div style={{ marginBottom: '20px' }}>
          <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: '0.85rem', marginBottom: '4px' }}>
            <span>Sprint Completion Rate</span>
            <span>{completionRate}%</span>
          </div>
          <div style={{ height: '8px', background: '#e2e8f0', borderRadius: '4px', overflow: 'hidden' }}>
            <div
              style={{
                width: `${completionRate}%`,
                height: '100%',
                background: 'linear-gradient(90deg, #2563eb, #16a34a)',
                transition: 'width 300ms ease',
              }}
            />
          </div>
        </div>

        {/* Actions */}
        <div style={{ display: 'flex', gap: '12px', justifyContent: 'flex-end', marginTop: '24px' }}>
          <button type="button" className="ghost-button" onClick={onClose}>
            Close
          </button>
          <button
            type="button"
            className="primary-button"
            onClick={handleDownloadPdf}
            disabled={generating}
            style={{
              display: 'inline-flex',
              alignItems: 'center',
              gap: '8px',
              background: '#2563eb',
              color: '#ffffff',
            }}
          >
            {generating ? 'Generating PDF...' : '📄 Download PDF Report'}
          </button>
        </div>
      </div>
    </div>
  )
}
